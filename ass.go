package vobsub

import (
	"bufio"
	"errors"
	"fmt"
	"image"
	"os"
	"path/filepath"
	"strconv"
	"strings"
)

// ASSOptions controls the generated text subtitle.
type ASSOptions struct {
	MarkerFormat string
	FontName     string
	FontSize     int
}

// ASSEvent is the subset of an ASS event needed for verification.
type ASSEvent struct {
	Index   int
	StartMS int64
	EndMS   int64
	X       int
	Y       int
	Color   string
	Alpha   int
	Text    string
}

// WriteASS emits marker-only Dialogue events plus machine-readable comments.
func WriteASS(path string, frame image.Point, cues []*Cue, opts ASSOptions) ([]ASSEvent, error) {
	if opts.MarkerFormat == "" {
		opts.MarkerFormat = "[VobSub %04d]"
	}
	if opts.FontName == "" {
		opts.FontName = "Arial"
	}
	if opts.FontSize <= 0 {
		opts.FontSize = 20
	}
	var events []ASSEvent
	var b strings.Builder
	fmt.Fprintf(&b, "[Script Info]\n")
	fmt.Fprintf(&b, "; Generated by vobsubtext. Marker text is not a transcription.\n")
	fmt.Fprintf(&b, "ScriptType: v4.00+\nPlayResX: %d\nPlayResY: %d\nWrapStyle: 2\nScaledBorderAndShadow: yes\n\n", frame.X, frame.Y)
	fmt.Fprintf(&b, "[V4+ Styles]\n")
	fmt.Fprintf(&b, "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding\n")
	fmt.Fprintf(&b, "Style: VobSubMarker,%s,%d,&H00FFFFFF,&H00FFFFFF,&H00000000,&H00000000,0,0,0,0,100,100,0,0,1,0,0,7,0,0,0,1\n\n", opts.FontName, opts.FontSize)
	fmt.Fprintf(&b, "[Events]\n")
	fmt.Fprintf(&b, "Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text\n")

	for _, cue := range cues {
		if !cue.Migratable {
			continue
		}
		color, ok := cue.DominantColour()
		if !ok {
			continue
		}
		start := round10(cue.StartMS)
		end := round10(cue.EndMS)
		if end <= start {
			end = start + 10
		}
		rgb, err := parseHexRGB(color.RGB)
		if err != nil {
			continue
		}
		text := fmt.Sprintf(opts.MarkerFormat, cue.Index)
		text = strings.ReplaceAll(text, "\r", " ")
		text = strings.ReplaceAll(text, "\n", " ")
		text = strings.NewReplacer("\\", "/", "{", "(", "}", ")").Replace(text)
		alpha := 255 - color.Alpha
		if alpha < 0 {
			alpha = 0
		}
		if alpha > 255 {
			alpha = 255
		}
		rect := cue.State.Rect
		fmt.Fprintf(&b, "Comment: 0,%s,%s,VobSubMarker,%04d,0,0,0,,source_rect=(%d,%d,%d,%d); dominant=%s; flags=%s\n",
			formatASSTime(start), formatASSTime(end), cue.Index,
			rect.X, rect.Y, rect.Width, rect.Height, color.RGB, flagList(cue.Flags))
		fmt.Fprintf(&b, "Dialogue: 0,%s,%s,VobSubMarker,%04d,0,0,0,,{\\an7\\pos(%d,%d)\\c&H%02X%02X%02X&\\1a&H%02X&}%s\n",
			formatASSTime(start), formatASSTime(end), cue.Index,
			rect.X, rect.Y, rgb.B, rgb.G, rgb.R, alpha, text)
		events = append(events, ASSEvent{
			Index: cue.Index, StartMS: start, EndMS: end,
			X: rect.X, Y: rect.Y, Color: color.RGB, Alpha: alpha, Text: text,
		})
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return nil, err
	}
	if err := os.WriteFile(path, []byte(b.String()), 0o644); err != nil {
		return nil, err
	}
	return events, nil
}

// ASSFile is the verification view of a generated ASS file.
type ASSFile struct {
	Path   string
	Frame  image.Point
	Events []ASSEvent
	SHA256 string
}

// ParseASS reads the generated subset of ASS used by this package.
func ParseASS(path string) (*ASSFile, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	out := &ASSFile{Path: path}
	var fields []string
	section := ""
	scanner := bufio.NewScanner(f)
	scanner.Buffer(make([]byte, 4096), 1024*1024)
	for scanner.Scan() {
		line := strings.TrimSpace(strings.TrimPrefix(scanner.Text(), "\ufeff"))
		if strings.HasPrefix(line, "[") && strings.HasSuffix(line, "]") {
			section = strings.ToLower(line)
			continue
		}
		switch section {
		case "[script info]":
			key, val, ok := strings.Cut(line, ":")
			if !ok {
				continue
			}
			switch strings.ToLower(strings.TrimSpace(key)) {
			case "playresx":
				out.Frame.X, _ = strconv.Atoi(strings.TrimSpace(val))
			case "playresy":
				out.Frame.Y, _ = strconv.Atoi(strings.TrimSpace(val))
			}
		case "[events]":
			if strings.HasPrefix(strings.ToLower(line), "format:") {
				fields = splitFields(line)
				continue
			}
			if !strings.HasPrefix(strings.ToLower(line), "dialogue:") || len(fields) == 0 {
				continue
			}
			values, err := splitEvent(line, fields)
			if err != nil {
				return nil, fmt.Errorf("%s: %w", path, err)
			}
			event, err := parseASSEvent(values)
			if err != nil {
				return nil, fmt.Errorf("%s: %w", path, err)
			}
			out.Events = append(out.Events, event)
		}
	}
	if err := scanner.Err(); err != nil {
		return nil, err
	}
	if out.Frame.X <= 0 || out.Frame.Y <= 0 {
		return nil, errors.New("ASS missing PlayResX/PlayResY")
	}
	out.SHA256, err = fileSHA256(path)
	if err != nil {
		return nil, err
	}
	return out, nil
}

func splitFields(format string) []string {
	_, rest, _ := strings.Cut(format, ":")
	parts := strings.Split(rest, ",")
	for i := range parts {
		parts[i] = strings.ToLower(strings.TrimSpace(parts[i]))
	}
	return parts
}

func splitEvent(line string, fields []string) (map[string]string, error) {
	_, rest, ok := strings.Cut(line, ":")
	if !ok {
		return nil, errors.New("event missing colon")
	}
	parts := strings.SplitN(rest, ",", len(fields))
	if len(parts) != len(fields) {
		return nil, fmt.Errorf("event has %d fields, want %d", len(parts), len(fields))
	}
	out := make(map[string]string, len(fields))
	for i, field := range fields {
		out[field] = strings.TrimSpace(parts[i])
	}
	return out, nil
}

func parseASSEvent(v map[string]string) (ASSEvent, error) {
	start, err := parseASSTime(v["start"])
	if err != nil {
		return ASSEvent{}, err
	}
	end, err := parseASSTime(v["end"])
	if err != nil {
		return ASSEvent{}, err
	}
	name := strings.TrimSpace(v["name"])
	index, _ := strconv.Atoi(name)
	text := v["text"]
	x, y := parsePos(text)
	color := parsePrimaryColor(text)
	alpha := parsePrimaryAlpha(text)
	return ASSEvent{
		Index: index, StartMS: start, EndMS: end, X: x, Y: y,
		Color: color, Alpha: alpha, Text: visibleText(text),
	}, nil
}

func formatASSTime(ms int64) string {
	if ms < 0 {
		ms = 0
	}
	cs := ms / 10
	h := cs / 360000
	cs %= 360000
	m := cs / 6000
	cs %= 6000
	s := cs / 100
	cs %= 100
	return fmt.Sprintf("%d:%02d:%02d.%02d", h, m, s, cs)
}

func parseASSTime(text string) (int64, error) {
	parts := strings.Split(strings.TrimSpace(text), ":")
	if len(parts) != 3 {
		return 0, fmt.Errorf("invalid ASS time %q", text)
	}
	h, err1 := strconv.Atoi(parts[0])
	m, err2 := strconv.Atoi(parts[1])
	secText, csText, ok := strings.Cut(parts[2], ".")
	if !ok {
		return 0, fmt.Errorf("invalid ASS time %q", text)
	}
	seconds, err3 := strconv.Atoi(secText)
	if len(csText) == 1 {
		csText += "0"
	}
	if len(csText) != 2 {
		return 0, fmt.Errorf("invalid ASS time %q", text)
	}
	centis, err4 := strconv.Atoi(csText)
	if err1 != nil || err2 != nil || err3 != nil || err4 != nil ||
		h < 0 || m < 0 || m > 59 || seconds < 0 || seconds > 59 ||
		centis < 0 || centis > 99 {
		return 0, fmt.Errorf("invalid ASS time %q", text)
	}
	return int64(((h*60+m)*60+seconds)*1000 + centis*10), nil
}

func parsePos(text string) (int, int) {
	i := strings.Index(strings.ToLower(text), "\\pos(")
	if i < 0 {
		return 0, 0
	}
	rest := text[i+5:]
	j := strings.IndexByte(rest, ')')
	if j < 0 {
		return 0, 0
	}
	xy := strings.SplitN(rest[:j], ",", 2)
	if len(xy) != 2 {
		return 0, 0
	}
	x, _ := strconv.Atoi(strings.TrimSpace(xy[0]))
	y, _ := strconv.Atoi(strings.TrimSpace(xy[1]))
	return x, y
}

func parsePrimaryColor(text string) string {
	lower := strings.ToLower(text)
	i := strings.Index(lower, "\\c&h")
	if i < 0 {
		return ""
	}
	rest := lower[i+4:]
	j := strings.IndexByte(rest, '&')
	if j < 0 || len(rest[:j]) != 6 {
		return ""
	}
	n, err := strconv.ParseUint(rest[:j], 16, 32)
	if err != nil {
		return ""
	}
	return fmt.Sprintf("#%02X%02X%02X", n&0xff, (n>>8)&0xff, (n>>16)&0xff)
}

func parsePrimaryAlpha(text string) int {
	lower := strings.ToLower(text)
	i := strings.Index(lower, "\\1a&h")
	if i < 0 {
		return 0
	}
	rest := lower[i+5:]
	j := strings.IndexByte(rest, '&')
	if j < 0 {
		return 0
	}
	n, _ := strconv.ParseInt(rest[:j], 16, 32)
	return int(n)
}

func visibleText(text string) string {
	if i := strings.LastIndexByte(text, '}'); i >= 0 {
		return text[i+1:]
	}
	return text
}

func parseHexRGB(text string) (RGB, error) {
	text = strings.TrimPrefix(strings.TrimSpace(text), "#")
	if len(text) != 6 {
		return RGB{}, fmt.Errorf("invalid RGB %q", text)
	}
	n, err := strconv.ParseUint(text, 16, 32)
	if err != nil {
		return RGB{}, err
	}
	return RGB{uint8(n >> 16), uint8(n >> 8), uint8(n)}, nil
}

func round10(ms int64) int64 {
	if ms < 0 {
		return 0
	}
	return (ms + 5) / 10 * 10
}

func flagList(flags []Flag) string {
	parts := make([]string, len(flags))
	for i, flag := range flags {
		parts[i] = string(flag)
	}
	return strings.Join(parts, "|")
}
