const glyphScale = 2

// drawText renders s at (x, y) using the pixel font. Returns the width.
func drawText(img *canvas, x, y int, s string, c color.RGBA) int {
	start := x
	for _, r := range s {
		g, ok := glyphs[r]
		if !ok {
			g = glyphs[' ']
		}
		for row := 0; row < 7; row++ {
			for col := 0; col < 5; col++ {
				if g[row][col] == '#' {
					img.fillRect(x+col*glyphScale, y+row*glyphScale, glyphScale, glyphScale, c)
				}
			}
		}
		x += 6 * glyphScale
	}
	return x - start
}

// textWidth returns the pixel width of s without drawing.
func textWidth(s string) int { return len([]rune(s)) * 6 * glyphScale }
