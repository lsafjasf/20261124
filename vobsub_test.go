// rleLine encodes one line of pixels (values 0..3) into VobSub RLE nibbles.
func rleLine(pix []uint8) []byte {
	var nibbles []int
	for x := 0; x < len(pix); {
		run := 1
		for x+run < len(pix) && pix[x+run] == pix[x] && run < 0x3FFF {
			run++
		}
		code := run<<2 | int(pix[x])
		switch {
		case code < 0x10:
			nibbles = append(nibbles, code)
		case code < 0x40:
			nibbles = append(nibbles, code>>4, code&0xF)
		case code < 0x100:
			nibbles = append(nibbles, code>>8, code>>4&0xF, code&0xF)
		default:
			nibbles = append(nibbles, code>>12, code>>8&0xF, code>>4&0xF, code&0xF)
		}
		x += run
	}
	if len(nibbles)%2 == 1 {
		nibbles = append(nibbles, 0)
	}
	out := make([]byte, len(nibbles)/2)
	for i := range out {
		out[i] = byte(nibbles[2*i]<<4 | nibbles[2*i+1])
	}
	return out
}

// buildSPU builds a complete SPU packet for a w*h bitmap drawn from rows of
// color slots; each row must be w bytes.
func buildSPU(w, h int, rows [][]uint8) []byte {
	var even, odd []byte
	for y := 0; y < h; y++ {
		if y%2 == 0 {
			even = append(even, rleLine(rows[y])...)
		} else {
			odd = append(odd, rleLine(rows[y])...)
		}
	}
	ctrl := []byte{
		0x00, 0x00, // delay
		0x03, 0x32, 0x10, // palette slots -> palette entries 3,2,1,0
		0x04, 0x0F, 0xFF, // alpha: slot0 transparent, rest opaque
		0x05, // coords (0,0)-(w-1,h-1)
		0x00, byte((w - 1) >> 8), byte(w - 1),
		0x00, byte((h - 1) >> 8), byte(h - 1),
		0x06, 0x00, 0x00, 0x00, 0x00, // RLE offsets patched below
		0xFF,
	}
	if len(ctrl)%2 == 1 {
		ctrl = append(ctrl, 0x00)
	}
	offEven := 4
	offOdd := 4 + len(even)
	pktSize := 4 + len(even) + len(odd) + len(ctrl)
	pkt := make([]byte, 0, pktSize)
	pkt = append(pkt, byte(pktSize>>8), byte(pktSize), byte((pktSize-len(ctrl))>>8), byte(pktSize-len(ctrl)))
	pkt = append(pkt, even...)
	pkt = append(pkt, odd...)
	// patch RLE offsets into the control block (after 0x06 at index 15)
	binary.BigEndian.PutUint16(ctrl[16:18], uint16(offEven))
	binary.BigEndian.PutUint16(ctrl[18:20], uint16(offOdd))
	pkt = append(pkt, ctrl...)
	return pkt
}

// wrapPES wraps an SPU packet in a private_stream_1 PES with pack header.
func wrapPES(spu []byte, langIdx int) []byte {
	payload := append([]byte{0x20 + byte(langIdx)}, spu...)
	pes := make([]byte, 0, 6+3+len(payload))
	pes = append(pes, 0x00, 0x00, 0x01, 0xBD)
	pes = append(pes, byte((3+len(payload))>>8), byte(3+len(payload)))
	pes = append(pes, 0x80, 0x00, 0x00) // no PTS, header_data_length 0
	pes = append(pes, payload...)
	pack := []byte{0x00, 0x00, 0x01, 0xBA, 0x44, 0x00, 0x04, 0x00, 0x04, 0x01, 0x89, 0xC3, 0xF8, 0x00}
	return append(pack, pes...)
}

// writeFixture builds a .sub with 4 packets and returns it plus entry offsets.
// Packet layout: 0=lang0 ok, 1=lang1 ok (same timestamp as 0), 2=lang0 ok,
// then a truncated tail (PES header promises more than the file holds).
func writeFixture(t *testing.T) (subPath string, offsets []int64) {
	t.Helper()
	rows := func(c uint8) [][]uint8 {
		r := make([][]uint8, 8)
		for y := range r {
			r[y] = make([]uint8, 16)
			for x := range r[y] {
				if x >= y && x < 16-y {
					r[y][x] = c
				}
			}
		}
		return r
	}
	p0 := wrapPES(buildSPU(16, 8, rows(1)), 0)
	p1 := wrapPES(buildSPU(16, 8, rows(2)), 1)
	p2 := wrapPES(buildSPU(16, 8, rows(3)), 0)
	var sub []byte
	for _, p := range [][]byte{p0, p1, p2} {
		offsets = append(offsets, int64(len(sub)))
		sub = append(sub, p...)
	}
	// truncated packet: full header, half the payload
	offsets = append(offsets, int64(len(sub)))
	sub = append(sub, p0[:len(p0)/2]...)
	// offset beyond EOF
	offsets = append(offsets, int64(len(sub))+0x100)

	subPath = filepath.Join(t.TempDir(), "movie.sub")
	if err := os.WriteFile(subPath, sub, 0o644); err != nil {
		t.Fatal(err)
	}
	return subPath, offsets
}

const idxTemplate = `# VobSub index file, generated by test
size: 720x480
palette: 000000, f0f0f0, cccccc, 999999, 3333fa, 1111bb, fa3333, bb1111, 33fa33, 11bb11, fafa33, bbbb11, fa33fa, bb11bb, 33fafa, 11bbbb

id: en, index: 0
timestamp: 00:00:01:000, filepos: %09x
timestamp: 00:00:04:000, filepos: %09x
timestamp: 00:00:07:000, filepos: %09x
timestamp: 00:00:10:000, filepos: %09x
timestamp: 00:00:13:000, filepos: %09x

id: fr, index: 1
timestamp: 00:00:01:000, filepos: %09x
`

func loadFixture(t *testing.T) (*Idx, *os.File, int64, []int64) {
	t.Helper()
	subPath, offsets := writeFixture(t)
	idxText := fmt.Sprintf(idxTemplate,
		offsets[0], offsets[1], offsets[2], offsets[3], offsets[4], offsets[1])
	idx, err := ParseIdx(strings.NewReader(idxText))
	if err != nil {
		t.Fatalf("ParseIdx: %v", err)
	}
	f, err := os.Open(subPath)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { f.Close() })
	st, _ := f.Stat()
	return idx, f, st.Size(), offsets
}

func TestParseIdx(t *testing.T) {
	idx, _, _, _ := loadFixture(t)
	if len(idx.Entries) != 6 {
		t.Fatalf("want 6 entries, got %d", len(idx.Entries))
	}
	if idx.Entries[5].LangIdx != 1 || idx.Entries[5].LangID != "fr" {
		t.Fatalf("entry 5 should be fr/index 1, got %+v", idx.Entries[5])
	}
	if idx.Palette[1] != [3]uint8{0xf0, 0xf0, 0xf0} {
		t.Fatalf("palette[1] wrong: %v", idx.Palette[1])
	}
}

func TestDecodeOK(t *testing.T) {
	idx, f, size, offsets := loadFixture(t)
	e := idx.Entries[0]
	spu, start, end, err := readSPU(f, e, size)
	if err != nil {
		t.Fatalf("readSPU: %v", err)
	}
	if start != offsets[0] {
		t.Fatalf("byte start: want 0x%x, got 0x%x", offsets[0], start)
	}
	sub, err := decodeSPU(e, spu, start, end)
	if err != nil {
		t.Fatalf("decodeSPU: %v", err)
	}
	if sub.Width != 16 || sub.Height != 8 {
		t.Fatalf("size: want 16x8, got %dx%d", sub.Width, sub.Height)
	}
	// row 4: pixels 4..11 are color 1, edges transparent
	if sub.Pixels[4*16+0] != 0 || sub.Pixels[4*16+5] != 1 || sub.Pixels[4*16+15] != 0 {
		t.Fatalf("row 4 pixels wrong: %v", sub.Pixels[4*16:4*16+16])
	}
	if sub.Colors[1] != 2 || sub.Alpha[0] != 0 || sub.Alpha[1] != 255 {
		t.Fatalf("colors/alpha wrong: %v %v", sub.Colors, sub.Alpha)
	}
	var pngBuf bytes.Buffer
	if err := RenderPNG(&pngBuf, sub, &idx.Palette); err != nil {
		t.Fatalf("RenderPNG: %v", err)
	}
	if !bytes.HasPrefix(pngBuf.Bytes(), []byte{0x89, 'P', 'N', 'G'}) {
		t.Fatal("preview is not a PNG")
	}
	if art := ASCIIArt(sub); !strings.Contains(art, ".") {
		t.Fatalf("ASCII preview empty:\n%s", art)
	}
}

func TestErrorsAttributedToEntries(t *testing.T) {
	idx, f, size, _ := loadFixture(t)
	cases := []struct {
		entry   int
		wantMsg string
	}{
		{1, "multi-language"}, // en entry points at fr packet
		{3, "truncated"},      // PES length runs past EOF
		{4, "beyond .sub"},    // filepos past EOF
	}
	for _, tc := range cases {
		e := idx.Entries[tc.entry]
		_, _, _, err := readSPU(f, e, size)
		if err == nil {
			t.Fatalf("entry %d: expected error", tc.entry)
		}
		ee, ok := err.(*EntryError)
		if !ok {
			t.Fatalf("entry %d: error not attributed: %v", tc.entry, err)
		}
		if ee.Entry.Index != tc.entry {
			t.Fatalf("entry %d: error attributed to entry %d", tc.entry, ee.Entry.Index)
		}
		if !strings.Contains(err.Error(), tc.wantMsg) {
			t.Fatalf("entry %d: error %q missing %q", tc.entry, err, tc.wantMsg)
		}
		if !strings.Contains(err.Error(), e.Timestamp) {
			t.Fatalf("entry %d: error %q missing timestamp", tc.entry, err)
		}
	}
	// good entries must still decode, incl. the fr stream at the same timestamp
	for _, i := range []int{0, 2, 5} {
		e := idx.Entries[i]
		spu, s, en, err := readSPU(f, e, size)
		if err != nil {
			t.Fatalf("entry %d: %v", i, err)
		}
		if _, err := decodeSPU(e, spu, s, en); err != nil {
			t.Fatalf("entry %d decode: %v", i, err)
		}
	}
}

// TestWriteDemo regenerates testdata/movie.{idx,sub} when DEMO_DIR is set.
func TestWriteDemo(t *testing.T) {
	dir := os.Getenv("DEMO_DIR")
	if dir == "" {
		t.Skip("DEMO_DIR not set")
	}
	subPath, offsets := writeFixture(t)
	sub, err := os.ReadFile(subPath)
	if err != nil {
		t.Fatal(err)
	}
	idxText := fmt.Sprintf(idxTemplate,
		offsets[0], offsets[1], offsets[2], offsets[3], offsets[4], offsets[1])
	if err := os.MkdirAll(dir, 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dir, "movie.sub"), sub, 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dir, "movie.idx"), []byte(idxText), 0o644); err != nil {
		t.Fatal(err)
	}
}
